import argparse
import gc
from pathlib import Path

import joblib
import numpy as np

from .paths import ROOT
DEFAULT_BUNDLE = (
    ROOT / "artifacts" / "experiments"
    / "wav2vec2_wavlm_equal_ensemble_v1"
    / "fitted_model" / "ensemble_verified.joblib"
)

EMOTIONS = {
    "01": "neutral",
    "02": "calm",
    "03": "happy",
    "04": "sad",
    "05": "angry",
    "06": "fearful",
    "07": "disgust",
    "08": "surprised",
}


def extract_features(audio, sample_rate, metadata, allow_download=False):
    import torch
    with torch.inference_mode():
        return _extract_features(audio, sample_rate, metadata, allow_download)


def _extract_features(audio, sample_rate, metadata, allow_download=False):
    import torch
    from transformers import AutoFeatureExtractor, AutoModel
    revision = metadata.get("revision")
    if not revision:
        raise ValueError("The encoder revision must be pinned.")

    processor = AutoFeatureExtractor.from_pretrained(
        metadata["model_id"],
        revision=revision,
        local_files_only=not allow_download,
        trust_remote_code=False,
    )

    options = {
        "revision": revision,
        "local_files_only": not allow_download,
        "trust_remote_code": False,
    }
    if "use_safetensors" in metadata:
        options["use_safetensors"] = metadata["use_safetensors"]

    model = AutoModel.from_pretrained(metadata["model_id"], **options)
    model.eval()
    model.requires_grad_(False)

    if processor.sampling_rate != sample_rate:
        raise ValueError("Processor sample rate mismatch.")
    if processor.do_normalize != metadata["do_normalize"]:
        raise ValueError("Processor normalization mismatch.")

    inputs = processor(
        audio,
        sampling_rate=sample_rate,
        return_tensors="pt",
    )
    outputs = model(
        **inputs,
        output_hidden_states=True,
        return_dict=True,
    )

    layers = outputs.hidden_states[1:]
    if len(layers) != 12:
        raise ValueError("Expected twelve transformer layers.")

    features = torch.stack([
        layer[0].mean(dim=0) for layer in layers
    ]).mean(dim=0).cpu().numpy().astype(np.float32)

    if features.shape != (768,) or not np.isfinite(features).all():
        raise ValueError("Invalid audio features.")

    del outputs, layers, model, processor
    gc.collect()
    return features.reshape(1, -1)


def ordered_probabilities(classifier, features, labels):
    classes = classifier.classes_.tolist()
    if set(classes) != set(labels):
        raise ValueError("Classifier labels do not match the bundle.")

    order = [classes.index(label) for label in labels]
    probabilities = classifier.predict_proba(features)[0, order]

    if (
        not np.isfinite(probabilities).all()
        or np.any(probabilities < 0)
        or not np.isclose(probabilities.sum(), 1.0)
    ):
        raise ValueError("Invalid probabilities.")

    return probabilities


def main():
    parser = argparse.ArgumentParser(
        description="Predict speech emotion with the verified equal ensemble."
    )
    parser.add_argument("audio", type=Path)
    parser.add_argument("--bundle", type=Path, default=DEFAULT_BUNDLE)
    parser.add_argument("--allow-download", action="store_true", help="Download the pinned encoders if absent from the local cache.")
    args = parser.parse_args()

    import librosa
    import torch

    audio_path = args.audio.resolve()
    if not audio_path.is_file():
        raise SystemExit(f"Audio file not found: {audio_path}")
    if not args.bundle.is_file():
        raise SystemExit(f"Model bundle not found: {args.bundle}")

    # Load only a trusted bundle generated by this project.
    bundle = joblib.load(args.bundle)

    if not bundle.get("audio_verification", {}).get(
        "identical_predicted_labels", False
    ):
        raise SystemExit("Use the audio-verified bundle.")
    if bundle["pooling"] != "all_transformer_mean":
        raise SystemExit("Unsupported pooling method.")
    if bundle["weights"] != {"wav2vec2": 0.5, "wavlm": 0.5}:
        raise SystemExit("Expected equal ensemble weights.")

    labels = bundle["labels"]
    if labels != list(EMOTIONS):
        raise SystemExit("Unexpected label order.")

    sample_rate = bundle["sample_rate"]
    audio, rate = librosa.load(
        audio_path, sr=sample_rate, mono=True
    )
    if audio.size == 0 or not np.isfinite(audio).all():
        raise SystemExit("Audio is empty or contains invalid values.")
    if not np.any(audio):
        raise SystemExit("The recording is entirely silent.")

    torch.set_num_threads(4)
    probabilities = {}

    for name in ("wav2vec2", "wavlm"):
        print(f"Processing with {name}...", flush=True)
        features = extract_features(
            audio, rate, bundle["encoders"][name], args.allow_download
        )
        probabilities[name] = ordered_probabilities(
            bundle["classifiers"][name], features, labels
        )

    combined = (
        0.5 * probabilities["wav2vec2"]
        + 0.5 * probabilities["wavlm"]
    )
    winner = int(np.argmax(combined))

    print(f"\nAudio: {audio_path.name}")
    print(f"Duration: {len(audio) / rate:.2f} seconds")
    print(f"Predicted emotion: {EMOTIONS[labels[winner]]}")

    print("\nEmotion       wav2vec2    WavLM    Ensemble")
    for index in np.argsort(-combined):
        emotion = EMOTIONS[labels[index]]
        print(
            f"{emotion:<12} "
            f"{probabilities['wav2vec2'][index]:>9.3f} "
            f"{probabilities['wavlm'][index]:>8.3f} "
            f"{combined[index]:>11.3f}"
        )

    print("\nScores are model estimates, not guaranteed correctness.")
    print("This command performs inference, not an accuracy evaluation.")


if __name__ == "__main__":
    main()
